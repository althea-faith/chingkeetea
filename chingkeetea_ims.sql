
CREATE DATABASE IF NO T EXISTS chingkeetea_ims CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE chingkeetea_ims;
SET FOREIGN_KEY_CHECKS = 0;
DROP VIEW IF EXISTS v_branch_summary, v_stock_out_report, v_stock_in_report, v_low_stock_items, v_inventory_status;
DROP TABLE IF EXISTS reports, low_stock_alerts, stock_usage, stock_movements, stock_request_items, stock_requests, inventory, products, categories, users, branches, roles;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE roles (
  role_id   TINYINT UNSIGNED PRIMARY KEY,
  role_name VARCHAR(20) NOT NULL UNIQUE,
  CHECK (role_name IN ('head_admin','branch_admin','staff'))
) ENGINE=InnoDB;

CREATE TABLE branches (
  branch_id   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  branch_code VARCHAR(20) NOT NULL UNIQUE COMMENT 'used in emails: name@<code>.admin.com',
  branch_name VARCHAR(100) NOT NULL,
  address     VARCHAR(255),
  status      ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE users (
  user_id       INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(120) NOT NULL UNIQUE,
  password_hash CHAR(64) NOT NULL,
  role_id       TINYINT UNSIGNED NOT NULL,
  branch_id     INT UNSIGNED NULL COMMENT 'NULL only for head admin',
  status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  admin_key     INT UNSIGNED AS (IF(role_id = 2 AND status = 'active', branch_id, NULL)) STORED,
  UNIQUE KEY one_active_admin_per_branch (admin_key),
  CONSTRAINT fk_users_role   FOREIGN KEY (role_id)   REFERENCES roles(role_id),
  CONSTRAINT fk_users_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CHECK ((role_id = 1 AND branch_id IS NULL) OR (role_id <> 1 AND branch_id IS NOT NULL))
) ENGINE=InnoDB;

CREATE TABLE categories (
  category_id   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  category_name VARCHAR(60) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE products (
  product_id    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  sku           VARCHAR(20) NOT NULL UNIQUE,
  product_name  VARCHAR(100) NOT NULL,
  category_id   INT UNSIGNED NOT NULL,
  unit          VARCHAR(10) NOT NULL COMMENT 'kg, l, btl, tub, pcs, roll, pack',
  par_level     INT UNSIGNED NOT NULL COMMENT 'usual full stock per branch',
  reorder_level INT UNSIGNED NOT NULL COMMENT 'at or below = low stock',
  description   VARCHAR(255),
  status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories(category_id)
) ENGINE=InnoDB;

CREATE TABLE inventory (
  branch_id  INT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NOT NULL,
  quantity   INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (branch_id, product_id),
  CONSTRAINT fk_inv_branch  FOREIGN KEY (branch_id)  REFERENCES branches(branch_id),
  CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES products(product_id),
  CHECK (quantity >= 0)
) ENGINE=InnoDB;

CREATE TABLE stock_requests (
  request_id     INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  branch_id      INT UNSIGNED NOT NULL,
  requested_by   INT UNSIGNED NOT NULL,
  status         ENUM('pending','approved','rejected','cancelled','fulfilled') NOT NULL DEFAULT 'pending',
  notes          VARCHAR(255),
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by    INT UNSIGNED NULL,
  reviewed_at    DATETIME NULL,
  review_remarks VARCHAR(255),
  CONSTRAINT fk_req_branch   FOREIGN KEY (branch_id)    REFERENCES branches(branch_id),
  CONSTRAINT fk_req_by       FOREIGN KEY (requested_by) REFERENCES users(user_id),
  CONSTRAINT fk_req_reviewer FOREIGN KEY (reviewed_by)  REFERENCES users(user_id)
) ENGINE=InnoDB;

CREATE TABLE stock_request_items (
  request_item_id    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  request_id         INT UNSIGNED NOT NULL,
  product_id         INT UNSIGNED NOT NULL,
  quantity_requested INT UNSIGNED NOT NULL,
  quantity_approved  INT UNSIGNED NULL,
  UNIQUE KEY uq_request_product (request_id, product_id),
  CONSTRAINT fk_ri_request FOREIGN KEY (request_id) REFERENCES stock_requests(request_id) ON DELETE CASCADE,
  CONSTRAINT fk_ri_product FOREIGN KEY (product_id) REFERENCES products(product_id),
  CHECK (quantity_requested > 0)
) ENGINE=InnoDB;

CREATE TABLE stock_movements (
  movement_id   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  branch_id     INT UNSIGNED NOT NULL,
  product_id    INT UNSIGNED NOT NULL,
  movement_type ENUM('stock_in','stock_out','adjustment') NOT NULL,
  qty_change    INT NOT NULL COMMENT 'signed: stock-in +, stock-out -, adjustment +/-',
  reason        VARCHAR(255),
  request_id    INT UNSIGNED NULL,
  recorded_by   INT UNSIGNED NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_movements_branch_date (branch_id, created_at),
  KEY idx_movements_product (product_id),
  CONSTRAINT fk_mv_inventory FOREIGN KEY (branch_id, product_id) REFERENCES inventory(branch_id, product_id),
  CONSTRAINT fk_mv_request   FOREIGN KEY (request_id)  REFERENCES stock_requests(request_id),
  CONSTRAINT fk_mv_user      FOREIGN KEY (recorded_by) REFERENCES users(user_id),
  CHECK ((movement_type = 'stock_in' AND qty_change > 0) OR (movement_type = 'stock_out' AND qty_change < 0) OR movement_type = 'adjustment')
) ENGINE=InnoDB;

CREATE TABLE stock_usage (
  usage_id    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  branch_id   INT UNSIGNED NOT NULL,
  product_id  INT UNSIGNED NOT NULL,
  quantity    INT UNSIGNED NOT NULL,
  usage_date  DATE NOT NULL,
  notes       VARCHAR(255),
  recorded_by INT UNSIGNED NOT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NULL,
  CONSTRAINT fk_use_inventory FOREIGN KEY (branch_id, product_id) REFERENCES inventory(branch_id, product_id),
  CONSTRAINT fk_use_user      FOREIGN KEY (recorded_by) REFERENCES users(user_id),
  CHECK (quantity > 0)
) ENGINE=InnoDB;

CREATE TABLE low_stock_alerts (
  alert_id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  branch_id         INT UNSIGNED NOT NULL,
  product_id        INT UNSIGNED NOT NULL,
  quantity_at_alert INT NOT NULL,
  status            ENUM('open','resolved') NOT NULL DEFAULT 'open',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at       DATETIME NULL,
  KEY idx_alerts_open (status, branch_id),
  CONSTRAINT fk_alert_inventory FOREIGN KEY (branch_id, product_id) REFERENCES inventory(branch_id, product_id)
) ENGINE=InnoDB;

CREATE TABLE reports (
  report_id    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  report_type  ENUM('inventory','stock_in','stock_out') NOT NULL,
  branch_id    INT UNSIGNED NULL COMMENT 'NULL = all branches (head admin)',
  date_from    DATE NULL,
  date_to      DATE NULL,
  generated_by INT UNSIGNED NOT NULL,
  generated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rep_branch FOREIGN KEY (branch_id)    REFERENCES branches(branch_id),
  CONSTRAINT fk_rep_user   FOREIGN KEY (generated_by) REFERENCES users(user_id)
) ENGINE=InnoDB;

-- ===== Rules (triggers) =====
-- New branch or product automatically gets inventory rows (starting at 0).
CREATE TRIGGER trg_branch_inventory AFTER INSERT ON branches FOR EACH ROW
  INSERT INTO inventory(branch_id, product_id) SELECT NEW.branch_id, product_id FROM products;
CREATE TRIGGER trg_product_inventory AFTER INSERT ON products FOR EACH ROW
  INSERT INTO inventory(branch_id, product_id) SELECT branch_id, NEW.product_id FROM branches;

-- Every movement updates the branch inventory.
CREATE TRIGGER trg_movement_apply AFTER INSERT ON stock_movements FOR EACH ROW
  UPDATE inventory SET quantity = quantity + NEW.qty_change WHERE branch_id = NEW.branch_id AND product_id = NEW.product_id;

-- Recording stock usage deducts stock; correcting a usage entry adjusts it back.
CREATE TRIGGER trg_usage_deduct AFTER INSERT ON stock_usage FOR EACH ROW
  INSERT INTO stock_movements(branch_id, product_id, movement_type, qty_change, reason, recorded_by, created_at)
  VALUES (NEW.branch_id, NEW.product_id, 'stock_out', -NEW.quantity, CONCAT('Stock usage #', NEW.usage_id), NEW.recorded_by, NEW.created_at);
CREATE TRIGGER trg_usage_update AFTER UPDATE ON stock_usage FOR EACH ROW
  INSERT INTO stock_movements(branch_id, product_id, movement_type, qty_change, reason, recorded_by)
  SELECT NEW.branch_id, NEW.product_id, 'adjustment', OLD.quantity - NEW.quantity, CONCAT('Stock usage #', NEW.usage_id, ' corrected'), NEW.recorded_by
  FROM DUAL WHERE NEW.quantity <> OLD.quantity;

-- Low-stock alert opens at or below the reorder level and resolves once restocked.
CREATE TRIGGER trg_alert_open AFTER UPDATE ON inventory FOR EACH ROW
  INSERT INTO low_stock_alerts(branch_id, product_id, quantity_at_alert)
  SELECT NEW.branch_id, NEW.product_id, NEW.quantity FROM products p
  WHERE p.product_id = NEW.product_id AND NEW.quantity <= p.reorder_level
    AND NOT EXISTS (SELECT 1 FROM low_stock_alerts a WHERE a.branch_id = NEW.branch_id AND a.product_id = NEW.product_id AND a.status = 'open');
CREATE TRIGGER trg_alert_close AFTER UPDATE ON inventory FOR EACH ROW
  UPDATE low_stock_alerts SET status = 'resolved', resolved_at = NOW()
  WHERE branch_id = NEW.branch_id AND product_id = NEW.product_id AND status = 'open'
    AND NEW.quantity > (SELECT reorder_level FROM products WHERE product_id = NEW.product_id);

-- ===== Views for monitoring and reports =====
CREATE VIEW v_inventory_status AS
SELECT b.branch_id, b.branch_name, p.product_id, p.sku, p.product_name, c.category_name, p.unit,
       i.quantity, p.reorder_level,
       CASE WHEN i.quantity = 0 THEN 'out_of_stock' WHEN i.quantity <= p.reorder_level THEN 'low_stock' ELSE 'normal' END AS stock_status
FROM inventory i
JOIN branches b ON b.branch_id = i.branch_id
JOIN products p ON p.product_id = i.product_id
JOIN categories c ON c.category_id = p.category_id
WHERE p.status = 'active';

CREATE VIEW v_low_stock_items AS
SELECT * FROM v_inventory_status WHERE stock_status <> 'normal';

CREATE VIEW v_stock_in_report AS
SELECT m.created_at, b.branch_name, p.sku, p.product_name, m.qty_change AS quantity_in, p.unit, m.reason, u.full_name AS recorded_by
FROM stock_movements m
JOIN branches b ON b.branch_id = m.branch_id
JOIN products p ON p.product_id = m.product_id
LEFT JOIN users u ON u.user_id = m.recorded_by
WHERE m.movement_type = 'stock_in';

CREATE VIEW v_stock_out_report AS
SELECT m.created_at, b.branch_name, p.sku, p.product_name, -m.qty_change AS quantity_out, p.unit, m.reason, u.full_name AS recorded_by
FROM stock_movements m
JOIN branches b ON b.branch_id = m.branch_id
JOIN products p ON p.product_id = m.product_id
LEFT JOIN users u ON u.user_id = m.recorded_by
WHERE m.movement_type = 'stock_out';

CREATE VIEW v_branch_summary AS
SELECT branch_id, branch_name, COUNT(*) AS items,
       SUM(stock_status = 'low_stock') AS low_stock, SUM(stock_status = 'out_of_stock') AS out_of_stock, SUM(quantity) AS total_units
FROM v_inventory_status GROUP BY branch_id, branch_name;

